"""Shared schema building blocks.

Contract rules
--------------
* Timestamps are ISO-8601 **with** UTC offset (``2026-10-01T09:00:00+00:00``).
  The client converts to the user's timezone for display.
* ``id`` fields accept client-generated UUIDs on the way in and are always
  returned as UUID strings on the way out.
* Money/macro values are returned as numbers (Decimal is serialised as float in
  JSON by Pydantic); precision beyond 2 dp is irrelevant for nutrition.
"""

from __future__ import annotations

import uuid
from datetime import date, datetime, time
from typing import Annotated, Any, Generic, Literal, TypeVar

from pydantic import BaseModel, ConfigDict, Field, field_validator

T = TypeVar("T")

# ---- reusable annotated types ------------------------------------------------
UuidStr = Annotated[
    uuid.UUID,
    Field(description="UUID (UUIDv7 recommended — generated by the client)"),
]
LocalDate = Annotated[date, Field(description="Local calendar day, YYYY-MM-DD")]
LocalTime = Annotated[time, Field(description="Local wall clock time, HH:MM")]
UtcDateTime = Annotated[datetime, Field(description="Timezone-aware timestamp, stored in UTC")]
TagList = Annotated[list[str], Field(default_factory=list, max_length=32)]
ScopesList = Annotated[list[str], Field(default_factory=list, max_length=32)]


class ORMModel(BaseModel):
    """Base for response models built from SQLAlchemy rows."""

    model_config = ConfigDict(from_attributes=True, populate_by_name=True)


class ApiModel(BaseModel):
    """Base for request/response models with strict extra handling."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


class IdOut(ApiModel):
    id: uuid.UUID


class OkOut(ApiModel):
    ok: bool = True


class DeletedOut(ApiModel):
    ok: bool = True
    id: uuid.UUID


class Page(ApiModel, Generic[T]):
    items: list[T]
    total: int | None = None
    limit: int = 50
    offset: int = 0
    has_more: bool = False


class ErrorBody(ApiModel):
    code: str
    message: str
    details: dict[str, Any] | None = None


class ErrorResponse(ApiModel):
    error: ErrorBody


class HealthOut(ApiModel):
    status: Literal["ok", "degraded"]
    version: str
    env: str
    time_utc: datetime
    database: bool
    # pg_trgm works for Cyrillic text (i.e. the DB locale is a real UTF-8
    # locale). ``None`` = extension missing / unknown.
    fuzzy_search: bool | None = None
    scheduler: dict[str, Any] | None = None


class VersionOut(ApiModel):
    name: str
    version: str
    env: str
    api_prefix: str
    features: dict[str, bool]


class TimezoneHint(ApiModel):
    """Timezone the client detected, sent along to keep settings in sync."""

    timezone: str
    language: Literal["ru", "en"] | None = None

    @field_validator("timezone")
    @classmethod
    def _known(cls, value: str) -> str:
        from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

        try:
            ZoneInfo(value)
        except (ZoneInfoNotFoundError, ValueError, KeyError) as exc:  # pragma: no cover
            raise ValueError("unknown timezone") from exc
        return value


class SyncTimestamp(ApiModel):
    updated_at: datetime
    created_at: datetime


def page_params(limit: int = 50, offset: int = 0) -> tuple[int, int]:
    return max(1, min(limit, 200)), max(0, offset)
