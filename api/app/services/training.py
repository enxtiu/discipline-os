async def template_from_workout(
    db: AsyncSession, *, user_id: uuid.UUID, workout_id: uuid.UUID, template_id: uuid.UUID, name: str
) -> WorkoutTemplate:
    """Turn a finished workout into a template: its exercises, set counts and top sets."""
    existing = await db.get(WorkoutTemplate, template_id)
    if existing is not None:
        if existing.user_id != user_id:
            raise Conflict("This id is already used", code="id_conflict")
        return existing
    workout = await _own_workout(db, user_id, workout_id)
    await db.refresh(workout, attribute_names=["sets"])
    grouped: dict[uuid.UUID, list[WorkoutSet]] = defaultdict(list)
    for row in sorted(workout.sets, key=lambda r: (r.sort_order, r.set_index)):
        if not row.is_warmup:
            grouped[row.exercise_id].append(row)
    if not grouped:
        raise Unprocessable("This workout has no working sets", code="workout_empty")
    template = WorkoutTemplate(
        id=template_id, user_id=user_id, name=name, kind=workout.kind, items=[], description=None
    )
    for index, (exercise_id, sets) in enumerate(grouped.items()):
        top = max(sets, key=lambda r: (float(r.weight_kg or 0), r.reps or 0, r.duration_s or 0))
        template.items.append(
            WorkoutTemplateItem(
                user_id=user_id,
                exercise_id=exercise_id,
                sort_order=index,
                target_sets=min(len(sets), 20),
                target_reps=top.reps,
                target_weight_kg=top.weight_kg,
                target_duration_s=top.duration_s,
                target_distance_m=top.distance_m,
                rest_seconds=90,
            )
        )
    if workout.duration_s:
        template.estimated_minutes = max(1, round(workout.duration_s / 60))
    db.add(template)
    await db.flush()
    await db.refresh(template)
    return template


