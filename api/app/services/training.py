"""Training (stage 4): exercise library, templates, weekly plan, workouts, PRs.

Rules this module keeps:

* **Every query is scoped by the caller.** Library exercises (``is_global``) are
  readable by everyone; custom exercises, templates, plans, workouts, sets and
  records belong to one user.
* **Writes are idempotent by client UUID.** A workout's and a set's ``id`` is
  generated by the app; replaying a start, a set or a finish returns the same
  rows, so the offline queue can resend safely and in any order.
* **Burned calories are informational** and never touch the food budget. They
  are an estimate from MET values (Compendium of Physical Activities) — the
  *net* part ``(MET − 1) × kg × hours``, so resting energy that the daily
  target already contains is not counted twice.
* **Personal records** are events: a set that beats the best of every *other*
  completed workout. The first time an exercise is done sets the baseline and
  is not a record. Bests are always recomputed from the sets themselves, so
  deleting a workout can never leave a stale "best".
"""

