async def body_weight_on(db: AsyncSession, user_id: uuid.UUID, day: date) -> float | None:
    measured = await db.scalar(
        select(BodyMetric.weight_kg)
        .where(BodyMetric.user_id == user_id, BodyMetric.measured_on <= day, BodyMetric.weight_kg.is_not(None))
        .order_by(BodyMetric.measured_on.desc())
        .limit(1)
    )
    if measured is not None:
        return float(measured)
    configured = await db.scalar(select(UserSettings.weight_kg).where(UserSettings.user_id == user_id))
    return float(configured) if configured is not None else None


def estimate_kcal(workout: WorkoutLog, exercises: dict[uuid.UUID, Exercise], weight_kg: float | None) -> Decimal | None:
    """Net MET estimate: timed sets by their own duration, the rest by session time."""
    if not weight_kg:
        return None

    def net(met: float) -> float:
        return max(met - 1.0, 0.5)

    kcal = 0.0
    timed_seconds = 0
    strength_mets: list[float] = []
    for row in workout.sets:
        exercise = exercises.get(row.exercise_id)
        if exercise is None:
            continue
        if row.duration_s and (exercise.is_timed or exercise.exercise_type in CARDIO_TYPES):
            kcal += net(exercise.met) * weight_kg * row.duration_s / 3600
            timed_seconds += row.duration_s
        else:
            strength_mets.append(exercise.met)
    if strength_mets:
        count = len(strength_mets)
        seconds = workout.duration_s - timed_seconds if workout.duration_s else count * SECONDS_PER_SET
        seconds = min(max(seconds, count * 60), count * MAX_SECONDS_PER_SET)
        kcal += net(sum(strength_mets) / count) * weight_kg * seconds / 3600
    if not workout.sets and workout.duration_s:
        kcal += net(DEFAULT_MET[workout.kind]) * weight_kg * workout.duration_s / 3600
    if kcal <= 0:
        return None
    return Decimal(str(round(kcal)))


