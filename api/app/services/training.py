def log_mode(exercise: Exercise) -> str:
    """How a set of this exercise is entered."""
    if exercise.is_timed and exercise.exercise_type in CARDIO_TYPES:
        return "cardio"
    if exercise.is_timed:
        return "duration"
    if exercise.equipment == Equipment.BODYWEIGHT:
        return "reps"
    return "weight_reps"


def epley(weight_kg: float | None, reps: int | None) -> Decimal | None:
    """Estimated one-rep max. Only meaningful for 1–12 reps with a load."""
    if not weight_kg or not reps or reps < 1 or reps > MAX_EPLEY_REPS:
        return None
    value = float(weight_kg) if reps == 1 else float(weight_kg) * (1 + reps / 30)
    return Decimal(str(value)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def _f(value) -> float | None:
    return float(value) if value is not None else None


def week_start_for(day: date, week_start: int) -> date:
    """``week_start`` follows user settings: 1 = Monday, 0 = Sunday."""
    if week_start == 0:
        return day - timedelta(days=(day.weekday() + 1) % 7)
    return day - timedelta(days=day.weekday())


def _aware(value: datetime | None, tz: str | None) -> datetime:
    if value is None:
        return utcnow()
    if value.tzinfo is None:  # a local wall clock from the app
        return value.replace(tzinfo=get_zone(tz))
    return ensure_utc(value)


