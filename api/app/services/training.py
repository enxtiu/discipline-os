async def workout_view(db: AsyncSession, workout: WorkoutLog) -> WorkoutView:
    user_id = workout.user_id
    await db.refresh(workout, attribute_names=["sets"])
    template = None
    if workout.template_id is not None:
        template = await db.scalar(
            select(WorkoutTemplate).where(WorkoutTemplate.id == workout.template_id, WorkoutTemplate.user_id == user_id)
        )
    order: list[uuid.UUID] = []
    # an in-progress workout shows the whole plan; a finished one only what was done
    if template is not None and workout.status == WorkoutStatus.IN_PROGRESS:
        order.extend(item.exercise_id for item in template.items)
    for row in sorted(workout.sets, key=lambda r: (r.sort_order, r.set_index, r.created_at)):
        if row.exercise_id not in order:
            order.append(row.exercise_id)
    exercises = {}
    if order:
        rows = (await db.scalars(select(Exercise).where(Exercise.id.in_(order), _visible(user_id)))).all()
        exercises = {row.id: row for row in rows}
        order = [exercise_id for exercise_id in order if exercise_id in exercises]
    records = (
        await db.scalars(
            select(PersonalRecord)
            .where(PersonalRecord.workout_log_id == workout.id, PersonalRecord.user_id == user_id)
            .order_by(PersonalRecord.kind)
        )
    ).all()
    return WorkoutView(
        workout=workout,
        exercises=exercises,
        order=order,
        template=template,
        previous=await previous_sets(db, user_id, order, exclude_workout=workout.id),
        bests=await bests_for(db, user_id, order, exclude_workout=workout.id),
        records=list(records),
        body_weight_kg=await body_weight_on(db, user_id, workout.local_day),
    )


async def workout_briefs(db: AsyncSession, user_id: uuid.UUID, workouts: list[WorkoutLog]) -> list[WorkoutBrief]:
    if not workouts:
        return []
    ids = [workout.id for workout in workouts]
    rows = await db.execute(
        select(WorkoutSet.workout_log_id, WorkoutSet.exercise_id, func.min(WorkoutSet.sort_order).label("pos"))
        .where(WorkoutSet.user_id == user_id, WorkoutSet.workout_log_id.in_(ids))
        .group_by(WorkoutSet.workout_log_id, WorkoutSet.exercise_id)
        .order_by(WorkoutSet.workout_log_id, func.min(WorkoutSet.sort_order))
    )
    per_workout: dict[uuid.UUID, list[uuid.UUID]] = defaultdict(list)
    for row in rows:
        per_workout[row.workout_log_id].append(row.exercise_id)
    names = {}
    exercise_ids = {exercise_id for items in per_workout.values() for exercise_id in items}
    if exercise_ids:
        for row in await db.execute(
            select(Exercise.id, Exercise.name_ru, Exercise.name_en).where(Exercise.id.in_(exercise_ids))
        ):
            names[row.id] = row.name_ru or row.name_en or ""
    return [
        WorkoutBrief(workout=workout, exercise_names=[names.get(e, "") for e in per_workout.get(workout.id, [])][:4])
        for workout in workouts
    ]


async def list_workouts(
    db: AsyncSession, *, user_id: uuid.UUID, before: datetime | None, limit: int
) -> tuple[list[WorkoutBrief], bool]:
    conditions = [WorkoutLog.user_id == user_id, WorkoutLog.is_deleted.is_(False), WorkoutLog.status.in_(ACTIVE)]
    if before is not None:
        conditions.append(WorkoutLog.started_at < ensure_utc(before))
    rows = (
        await db.scalars(select(WorkoutLog).where(*conditions).order_by(WorkoutLog.started_at.desc()).limit(limit + 1))
    ).all()
    return await workout_briefs(db, user_id, list(rows[:limit])), len(rows) > limit


