def _done_workouts(user_id: uuid.UUID, exclude: uuid.UUID | None):
    conditions = [
        WorkoutLog.user_id == user_id,
        WorkoutLog.status == WorkoutStatus.COMPLETED,
        WorkoutLog.is_deleted.is_(False),
    ]
    if exclude is not None:
        conditions.append(WorkoutLog.id != exclude)
    return conditions


async def bests_for(
    db: AsyncSession, user_id: uuid.UUID, exercise_ids, *, exclude_workout: uuid.UUID | None = None
) -> dict[uuid.UUID, Bests]:
    """All-time bests per exercise over completed workouts (optionally all but one)."""
    ids = list(set(exercise_ids))
    if not ids:
        return {}
    working = and_(WorkoutSet.is_warmup.is_(False), WorkoutSet.exercise_id.in_(ids), WorkoutSet.user_id == user_id)
    rows = await db.execute(
        select(
            WorkoutSet.exercise_id,
            func.max(case((WorkoutSet.reps >= 1, WorkoutSet.weight_kg))).label("weight"),
            func.max(WorkoutSet.est_1rm_kg).label("e1rm"),
            func.max(WorkoutSet.reps).label("reps"),
            func.max(WorkoutSet.duration_s).label("duration"),
            func.max(WorkoutSet.distance_m).label("distance"),
        )
        .join(WorkoutLog, WorkoutLog.id == WorkoutSet.workout_log_id)
        .where(working, *_done_workouts(user_id, exclude_workout))
        .group_by(WorkoutSet.exercise_id)
    )
    out = {
        row.exercise_id: Bests(
            weight_kg=_f(row.weight),
            est_1rm_kg=_f(row.e1rm),
            reps=row.reps,
            duration_s=row.duration,
            distance_m=row.distance,
        )
        for row in rows
    }
    per_workout = (
        select(
            WorkoutSet.exercise_id.label("exercise_id"),
            func.sum(func.coalesce(WorkoutSet.weight_kg, 0) * func.coalesce(WorkoutSet.reps, 0)).label("volume"),
        )
        .join(WorkoutLog, WorkoutLog.id == WorkoutSet.workout_log_id)
        .where(working, *_done_workouts(user_id, exclude_workout))
        .group_by(WorkoutSet.exercise_id, WorkoutSet.workout_log_id)
        .subquery()
    )
    volumes = await db.execute(
        select(per_workout.c.exercise_id, func.max(per_workout.c.volume)).group_by(per_workout.c.exercise_id)
    )
    for exercise_id, volume in volumes:
        if volume and exercise_id in out:
            out[exercise_id].volume_kg = float(volume)
    return out


async def previous_sets(
    db: AsyncSession, user_id: uuid.UUID, exercise_ids, *, exclude_workout: uuid.UUID | None
) -> dict[uuid.UUID, tuple[date, list[WorkoutSet]]]:
    """Per exercise: the sets of the latest *other* completed workout that had it."""
    ids = list(set(exercise_ids))
    if not ids:
        return {}
    latest = (
        select(WorkoutSet.exercise_id, WorkoutLog.id.label("workout_id"), WorkoutLog.local_day)
        .join(WorkoutLog, WorkoutLog.id == WorkoutSet.workout_log_id)
        .where(
            WorkoutSet.user_id == user_id, WorkoutSet.exercise_id.in_(ids), *_done_workouts(user_id, exclude_workout)
        )
        .ext(distinct_on(WorkoutSet.exercise_id))
        .order_by(WorkoutSet.exercise_id, WorkoutLog.started_at.desc())
    )
    pairs = {row.exercise_id: (row.workout_id, row.local_day) for row in await db.execute(latest)}
    if not pairs:
        return {}
    sets = (
        await db.scalars(
            select(WorkoutSet)
            .where(
                WorkoutSet.user_id == user_id,
                tuple_(WorkoutSet.workout_log_id, WorkoutSet.exercise_id).in_(
                    [(workout_id, exercise_id) for exercise_id, (workout_id, _day) in pairs.items()]
                ),
            )
            .order_by(WorkoutSet.sort_order, WorkoutSet.set_index)
        )
    ).all()
    grouped: dict[uuid.UUID, list[WorkoutSet]] = defaultdict(list)
    for row in sets:
        grouped[row.exercise_id].append(row)
    return {exercise_id: (day, grouped.get(exercise_id, [])) for exercise_id, (_wid, day) in pairs.items()}


def _current(sets: list[WorkoutSet]) -> dict[str, tuple[float, WorkoutSet | None]]:
    """This workout's values per record kind for one exercise (working sets only)."""
    working = [row for row in sets if not row.is_warmup]
    values: dict[str, tuple[float, WorkoutSet | None]] = {}

    def top(key, rows):
        best = max(rows, key=key, default=None)
        if best is not None and key(best):
            return float(key(best)), best
        return None

    loaded = [row for row in working if row.weight_kg and row.reps and row.reps >= 1]
    for kind, key, rows in (
        ("weight", lambda r: float(r.weight_kg or 0), loaded),
        ("est_1rm", lambda r: float(r.est_1rm_kg or 0), working),
        ("reps", lambda r: r.reps or 0, working),
        ("duration", lambda r: r.duration_s or 0, working),
        ("distance", lambda r: r.distance_m or 0, working),
    ):
        found = top(key, rows)
        if found:
            values[kind] = found
    volume = sum(float(row.weight_kg or 0) * (row.reps or 0) for row in working)
    if volume:
        values["volume"] = (volume, None)
    return values


RECORD_KINDS = {
    "weight_reps": ("weight", "est_1rm", "volume"),
    "reps": ("reps",),
    "duration": ("duration",),
    "cardio": ("distance", "duration"),
}
RECORD_UNITS = {"weight": "kg", "est_1rm": "kg", "volume": "kg", "reps": "reps", "duration": "s", "distance": "m"}
BEST_FIELD = {
    "weight": "weight_kg",
    "est_1rm": "est_1rm_kg",
    "volume": "volume_kg",
    "reps": "reps",
    "duration": "duration_s",
    "distance": "distance_m",
}


async def _detect_records(db: AsyncSession, view_exercises: dict[uuid.UUID, Exercise], workout: WorkoutLog) -> int:
    """Replace this workout's record events with what it beats now."""
    await db.execute(delete(PersonalRecord).where(PersonalRecord.workout_log_id == workout.id))
    by_exercise: dict[uuid.UUID, list[WorkoutSet]] = defaultdict(list)
    for row in workout.sets:
        by_exercise[row.exercise_id].append(row)
    prior = await bests_for(db, workout.user_id, by_exercise, exclude_workout=workout.id)
    count = 0
    achieved_at = workout.ended_at or workout.started_at
    for exercise_id, sets in by_exercise.items():
        exercise = view_exercises.get(exercise_id)
        if exercise is None or exercise_id not in prior:
            continue  # first time: the baseline, not a record
        before = prior[exercise_id]
        current = _current(sets)
        for kind in RECORD_KINDS[log_mode(exercise)]:
            if kind not in current:
                continue
            value, row = current[kind]
            previous = getattr(before, BEST_FIELD[kind])
            if previous is None or value <= float(previous) + 1e-9:
                continue
            db.add(
                PersonalRecord(
                    user_id=workout.user_id,
                    exercise_id=exercise_id,
                    kind=kind,
                    value=Decimal(str(round(value, 2))),
                    previous_value=Decimal(str(round(float(previous), 2))),
                    unit=RECORD_UNITS[kind],
                    reps=row.reps if row is not None and kind in ("weight", "est_1rm") else None,
                    achieved_at=achieved_at,
                    workout_log_id=workout.id,
                    workout_set_id=row.id if row is not None else None,
                )
            )
            count += 1
    return count


