async def exercise_history(
    db: AsyncSession, *, user_id: uuid.UUID, exercise_id: uuid.UUID, limit: int = 12
) -> tuple[Exercise, Bests, list[PersonalRecord], list[tuple[WorkoutLog, list[WorkoutSet]]]]:
    exercise = await get_exercise(db, user_id, exercise_id)
    bests = (await bests_for(db, user_id, [exercise_id])).get(exercise_id, Bests())
    records = (
        await db.scalars(
            select(PersonalRecord)
            .where(PersonalRecord.user_id == user_id, PersonalRecord.exercise_id == exercise_id)
            .order_by(PersonalRecord.achieved_at.desc())
            .limit(20)
        )
    ).all()
    recent = (
        select(WorkoutLog.id)
        .join(WorkoutSet, WorkoutSet.workout_log_id == WorkoutLog.id)
        .where(WorkoutSet.exercise_id == exercise_id, *_done_workouts(user_id, None))
        .group_by(WorkoutLog.id, WorkoutLog.started_at)
        .order_by(WorkoutLog.started_at.desc())
        .limit(limit)
    )
    workout_ids = [row[0] for row in await db.execute(recent)]
    sessions: list[tuple[WorkoutLog, list[WorkoutSet]]] = []
    if workout_ids:
        workouts = (
            await db.scalars(
                select(WorkoutLog).where(WorkoutLog.id.in_(workout_ids)).order_by(WorkoutLog.started_at.desc())
            )
        ).all()
        sets = (
            await db.scalars(
                select(WorkoutSet).where(
                    WorkoutSet.workout_log_id.in_(workout_ids),
                    WorkoutSet.exercise_id == exercise_id,
                    WorkoutSet.user_id == user_id,
                )
            )
        ).all()
        grouped: dict[uuid.UUID, list[WorkoutSet]] = defaultdict(list)
        for row in sets:
            grouped[row.workout_log_id].append(row)
        sessions = [(workout, grouped.get(workout.id, [])) for workout in workouts]
    return exercise, bests, list(records), sessions


