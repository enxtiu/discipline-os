async def _own_workout(db: AsyncSession, user_id: uuid.UUID, workout_id: uuid.UUID) -> WorkoutLog:
    workout = await db.scalar(
        select(WorkoutLog).where(
            WorkoutLog.id == workout_id, WorkoutLog.user_id == user_id, WorkoutLog.is_deleted.is_(False)
        )
    )
    if workout is None:
        raise NotFound("Workout not found", code="workout_not_found")
    return workout


async def _recompute(db: AsyncSession, workout: WorkoutLog) -> dict[uuid.UUID, Exercise]:
    """Totals always; calories and records once the workout is completed."""
    await db.refresh(workout, attribute_names=["sets"])
    exercises = await _visible_exercise_map(db, workout.user_id, {row.exercise_id for row in workout.sets})
    working = [row for row in workout.sets if not row.is_warmup]
    workout.total_sets = len(working)
    workout.total_reps = sum(row.reps or 0 for row in working)
    workout.total_volume_kg = Decimal(
        str(round(sum(float(row.weight_kg or 0) * (row.reps or 0) for row in working), 2))
    )
    if workout.status == WorkoutStatus.COMPLETED:
        if workout.kcal_method != KcalMethod.MANUAL:
            weight = await body_weight_on(db, workout.user_id, workout.local_day)
            kcal = estimate_kcal(workout, exercises, weight)
            workout.kcal_burned = kcal
            workout.kcal_method = KcalMethod.MET if kcal is not None else KcalMethod.NONE
        workout.pr_count = await _detect_records(db, exercises, workout)
    await db.flush()
    return exercises


async def start_workout(db: AsyncSession, *, user_id: uuid.UUID, tz: str | None, payload) -> WorkoutLog:
    existing = await db.get(WorkoutLog, payload.id)
    if existing is not None:
        if existing.user_id != user_id:
            raise Conflict("This id is already used", code="id_conflict")
        return existing  # replayed start
    active = await db.scalar(
        select(WorkoutLog.id).where(
            WorkoutLog.user_id == user_id,
            WorkoutLog.status == WorkoutStatus.IN_PROGRESS,
            WorkoutLog.is_deleted.is_(False),
        )
    )
    if active is not None:
        raise Conflict(
            "Finish or discard the workout in progress first",
            code="workout_in_progress",
            details={"workout_id": str(active)},
        )
    template = None
    if payload.template_id is not None:
        template = await _own_template(db, user_id, payload.template_id)
        template.use_count += 1
    started_at = _aware(payload.started_at, tz)
    kind = payload.kind or (template.kind.value if template else "strength")
    stmt = (
        pg_insert(WorkoutLog)
        .values(
            id=payload.id,
            client_uuid=payload.id,
            user_id=user_id,
            template_id=template.id if template else None,
            title=payload.title or (template.name if template else None),
            kind=ExerciseType(kind),
            status=WorkoutStatus.IN_PROGRESS,
            started_at=started_at,
            local_day=local_day(started_at, tz),
            kcal_method=KcalMethod.NONE,
            source="app",
        )
        .on_conflict_do_nothing(index_elements=[WorkoutLog.id])
    )
    await db.execute(stmt)
    workout = await db.get(WorkoutLog, payload.id, populate_existing=True)
    if workout is None or workout.user_id != user_id:
        raise Conflict("This id is already used", code="id_conflict")
    log.info("workout_started", workout_id=str(workout.id), template=str(template.id) if template else None)
    return workout


async def upsert_set(
    db: AsyncSession, *, user_id: uuid.UUID, workout_id: uuid.UUID, set_id: uuid.UUID, payload
) -> WorkoutLog:
    workout = await _own_workout(db, user_id, workout_id)
    await get_exercise(db, user_id, payload.exercise_id)
    values = {
        "exercise_id": payload.exercise_id,
        "sort_order": payload.sort_order,
        "set_index": payload.set_index,
        "is_warmup": payload.is_warmup,
        "reps": payload.reps,
        "weight_kg": Decimal(str(payload.weight_kg)) if payload.weight_kg is not None else None,
        "rpe": payload.rpe,
        "duration_s": payload.duration_s,
        "distance_m": payload.distance_m,
        "rest_s": payload.rest_s,
        "note": payload.note,
        "est_1rm_kg": None if payload.is_warmup else epley(payload.weight_kg, payload.reps),
        "updated_at": utcnow(),
    }
    stmt = (
        pg_insert(WorkoutSet)
        .values(id=set_id, client_uuid=set_id, user_id=user_id, workout_log_id=workout.id, **values)
        .on_conflict_do_update(
            index_elements=[WorkoutSet.id],
            set_=values,
            where=and_(WorkoutSet.user_id == user_id, WorkoutSet.workout_log_id == workout.id),
        )
        .returning(WorkoutSet.id)
    )
    if (await db.execute(stmt)).scalar_one_or_none() is None:
        raise Conflict("This set id belongs to another workout", code="id_conflict")
    await _recompute(db, workout)
    return workout


