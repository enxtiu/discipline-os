async def week_plan(
    db: AsyncSession, *, user_id: uuid.UUID, start: date, today: date
) -> tuple[list[PlanDay], list[WeeklyPlan | None], dict[uuid.UUID, WorkoutTemplate]]:
    end = start + timedelta(days=6)
    rows = (
        await db.scalars(
            select(WeeklyPlan).where(
                WeeklyPlan.user_id == user_id,
                or_(WeeklyPlan.weekday.is_not(None), WeeklyPlan.plan_date.between(start, end)),
            )
        )
    ).all()
    recurring: list[WeeklyPlan | None] = [None] * 7
    dated: dict[date, WeeklyPlan] = {}
    for row in rows:
        if row.plan_date is not None:
            dated[row.plan_date] = row
        elif row.weekday is not None:
            recurring[row.weekday] = row
    template_ids = {row.template_id for row in rows if row.template_id}
    templates = {}
    if template_ids:
        found = await db.scalars(
            select(WorkoutTemplate).where(
                WorkoutTemplate.id.in_(template_ids),
                WorkoutTemplate.user_id == user_id,
                WorkoutTemplate.is_archived.is_(False),
            )
        )
        templates = {template.id: template for template in found}
    workouts = (
        await db.scalars(
            select(WorkoutLog)
            .where(
                WorkoutLog.user_id == user_id,
                WorkoutLog.is_deleted.is_(False),
                WorkoutLog.status.in_(ACTIVE),
                WorkoutLog.local_day.between(start, end),
            )
            .order_by(WorkoutLog.started_at)
        )
    ).all()
    briefs = await workout_briefs(db, user_id, list(workouts))
    by_day: dict[date, list[WorkoutBrief]] = defaultdict(list)
    for brief in briefs:
        by_day[brief.workout.local_day].append(brief)
    days = []
    for offset in range(7):
        day = start + timedelta(days=offset)
        row = dated.get(day) or recurring[day.weekday()]
        source = "date" if day in dated else "weekday" if row is not None else "none"
        days.append(
            PlanDay(
                day=day,
                source=source,
                row=row,
                template=templates.get(row.template_id) if row is not None and row.template_id else None,
                is_today=day == today,
                workouts=by_day.get(day, []),
            )
        )
    return days, recurring, templates


