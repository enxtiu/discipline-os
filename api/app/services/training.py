async def finish_workout(db: AsyncSession, *, user_id: uuid.UUID, workout_id: uuid.UUID, payload) -> WorkoutLog:
    workout = await _own_workout(db, user_id, workout_id)
    if workout.status == WorkoutStatus.COMPLETED:
        return workout  # replayed finish
    await db.refresh(workout, attribute_names=["sets"])
    if not workout.sets:
        raise Unprocessable("Log at least one set, or discard the workout", code="workout_empty")
    if payload.duration_s:
        workout.duration_s = payload.duration_s
        workout.ended_at = workout.started_at + timedelta(seconds=payload.duration_s)
    else:
        ended = ensure_utc(payload.ended_at) if payload.ended_at else utcnow()
        if ended < workout.started_at:
            raise Unprocessable("A workout cannot end before it started", code="workout_end_before_start")
        workout.ended_at = ended
        workout.duration_s = max(60, int((ended - workout.started_at).total_seconds()))
    if payload.rating is not None:
        workout.rating = payload.rating
    if payload.notes_md is not None:
        workout.notes_md = payload.notes_md
    workout.status = WorkoutStatus.COMPLETED
    await _recompute(db, workout)
    log.info(
        "workout_finished",
        workout_id=str(workout.id),
        sets=workout.total_sets,
        kcal=_f(workout.kcal_burned),
        records=workout.pr_count,
    )
    return workout


async def patch_workout(db: AsyncSession, *, user_id: uuid.UUID, workout_id: uuid.UUID, payload) -> WorkoutLog:
    workout = await _own_workout(db, user_id, workout_id)
    data = payload.model_dump(exclude_unset=True)
    for key in ("title", "notes_md", "rating"):
        if key in data:
            setattr(workout, key, data[key])
    if data.get("duration_s"):
        workout.duration_s = data["duration_s"]
        if workout.status == WorkoutStatus.COMPLETED:
            workout.ended_at = workout.started_at + timedelta(seconds=data["duration_s"])
    if data.get("kcal_auto"):
        workout.kcal_method = KcalMethod.NONE  # recompute below
    elif data.get("kcal_burned") is not None:
        workout.kcal_burned = Decimal(str(round(data["kcal_burned"])))
        workout.kcal_method = KcalMethod.MANUAL
    await _recompute(db, workout)
    return workout


