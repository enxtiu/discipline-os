def _visible(user_id: uuid.UUID):
    return or_(Exercise.is_global.is_(True), Exercise.user_id == user_id)


def _norm(column):
    return func.replace(func.lower(func.coalesce(column, "")), "ё", "е")


async def get_exercise(db: AsyncSession, user_id: uuid.UUID, exercise_id: uuid.UUID) -> Exercise:
    exercise = await db.scalar(select(Exercise).where(Exercise.id == exercise_id, _visible(user_id)))
    if exercise is None:
        raise NotFound("Exercise not found", code="exercise_not_found")
    return exercise


async def _visible_exercise_map(db: AsyncSession, user_id: uuid.UUID, ids) -> dict[uuid.UUID, Exercise]:
    wanted = set(ids)
    if not wanted:
        return {}
    rows = (await db.scalars(select(Exercise).where(Exercise.id.in_(wanted), _visible(user_id)))).all()
    found = {row.id: row for row in rows}
    missing = wanted - found.keys()
    if missing:
        raise NotFound("Exercise not found", code="exercise_not_found", details={"ids": sorted(map(str, missing))})
    return found


async def recent_exercise_ids(db: AsyncSession, user_id: uuid.UUID, limit: int = RECENT_EXERCISES) -> list[uuid.UUID]:
    rows = await db.execute(
        select(WorkoutSet.exercise_id, func.max(WorkoutSet.created_at).label("last"))
        .where(WorkoutSet.user_id == user_id)
        .group_by(WorkoutSet.exercise_id)
        .order_by(func.max(WorkoutSet.created_at).desc())
        .limit(limit)
    )
    return [row.exercise_id for row in rows]


async def search_exercises(
    db: AsyncSession,
    *,
    user_id: uuid.UUID,
    query: str = "",
    muscle_group: str | None = None,
    equipment: str | None = None,
    exercise_type: str | None = None,
    limit: int = SEARCH_LIMIT,
) -> list[Exercise]:
    """Library + own exercises. Small table: rank everything that matches."""
    filters = [_visible(user_id), Exercise.is_archived.is_(False)]
    if muscle_group:
        filters.append(
            or_(
                Exercise.muscle_group == MuscleGroup(muscle_group),
                Exercise.secondary_muscles.contains([muscle_group]),
            )
        )
    if equipment:
        filters.append(Exercise.equipment == Equipment(equipment))
    if exercise_type:
        filters.append(Exercise.exercise_type == ExerciseType(exercise_type))

    q = " ".join(query.split())[:100]
    own_first = case((Exercise.user_id == user_id, 0), else_=1)
    if not q:
        stmt = (
            select(Exercise)
            .where(*filters)
            .order_by(own_first, Exercise.muscle_group, func.coalesce(Exercise.name_ru, Exercise.name_en))
            .limit(limit)
        )
        return list((await db.scalars(stmt)).all())

    nq = q.lower().replace("ё", "е")
    q_ru = func.plainto_tsquery(cast("russian", REGCONFIG), q)
    q_en = func.plainto_tsquery(cast("english", REGCONFIG), q)
    name_ru, name_en, aliases = _norm(Exercise.name_ru), _norm(Exercise.name_en), _norm(Exercise.aliases_text)
    similarity = func.greatest(func.similarity(name_ru, nq), func.similarity(name_en, nq))
    substring = or_(name_ru.contains(nq, autoescape=True), name_en.contains(nq, autoescape=True))
    alias_hit = aliases.contains(nq, autoescape=True)
    # the words people actually type ("жим лёжа", "bench") are aliases: an exact one wins
    alias_values = func.jsonb_array_elements_text(Exercise.aliases).table_valued("value")
    alias_exact = (
        select(1)
        .select_from(alias_values)
        .where(func.replace(func.lower(alias_values.c.value), "ё", "е") == nq)
        .exists()
    )
    name_exact = or_(name_ru == nq, name_en == nq)
    fts = or_(Exercise.search_vector_ru.op("@@")(q_ru), Exercise.search_vector_en.op("@@")(q_en))
    score = (
        similarity
        + case((substring, 0.6), else_=0.0)
        + case((or_(name_ru.startswith(nq, autoescape=True), name_en.startswith(nq, autoescape=True)), 0.3), else_=0.0)
        + case((alias_hit, 0.4), else_=0.0)
        + case((or_(alias_exact, name_exact), 1.0), else_=0.0)
        + case((fts, 0.3), else_=0.0)
        + case((Exercise.user_id == user_id, 1.0), else_=0.0)
    )
    stmt = (
        select(Exercise)
        .where(*filters, or_(substring, alias_hit, fts, similarity >= 0.3))
        .order_by(score.desc(), func.coalesce(Exercise.name_ru, Exercise.name_en))
        .limit(limit)
    )
    return list((await db.scalars(stmt)).all())


async def create_exercise(db: AsyncSession, *, user_id: uuid.UUID, payload) -> Exercise:
    if payload.id is not None:
        existing = await db.get(Exercise, payload.id)
        if existing is not None:
            if existing.user_id != user_id:
                raise Conflict("This id is already used", code="id_conflict")
            return existing
    kind = ExerciseType(payload.exercise_type)
    exercise = Exercise(
        id=payload.id or uuid.uuid4(),
        user_id=user_id,
        is_global=False,
        name_ru=payload.name_ru,
        name_en=payload.name_en,
        aliases=[alias.strip() for alias in payload.aliases if alias.strip()],
        muscle_group=MuscleGroup(payload.muscle_group),
        equipment=Equipment(payload.equipment),
        exercise_type=kind,
        is_timed=payload.is_timed or kind in CARDIO_TYPES,
        is_unilateral=payload.is_unilateral,
        met=payload.met or DEFAULT_MET[kind],
        source="user",
    )
    db.add(exercise)
    await db.flush()
    await db.refresh(exercise)
    return exercise


async def update_exercise(db: AsyncSession, *, user_id: uuid.UUID, exercise_id: uuid.UUID, payload) -> Exercise:
    exercise = await db.scalar(select(Exercise).where(Exercise.id == exercise_id, Exercise.user_id == user_id))
    if exercise is None:
        raise NotFound("Exercise not found (library exercises are read-only)", code="exercise_not_found")
    data = payload.model_dump(exclude_unset=True)
    for key, enum in (("muscle_group", MuscleGroup), ("equipment", Equipment), ("exercise_type", ExerciseType)):
        if data.get(key) is not None:
            data[key] = enum(data[key])
    if "aliases" in data and data["aliases"] is not None:
        data["aliases"] = [alias.strip() for alias in data["aliases"] if alias.strip()]
    for key, value in data.items():
        if value is None and key not in ("name_ru", "name_en"):
            continue
        setattr(exercise, key, value)
    if not (exercise.name_ru or exercise.name_en):
        raise Unprocessable("An exercise needs a name", code="exercise_name_required")
    await db.flush()
    await db.refresh(exercise)
    return exercise


