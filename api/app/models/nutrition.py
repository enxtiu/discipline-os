class Recipe(UuidPkMixin, TimestampMixin, Base):
    """A dish built from foods. Macros are denormalised on write."""

    __tablename__ = "recipes"

    user_id: Mapped[uuid.UUID] = mapped_column(
        UuidType, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    notes_md: Mapped[str | None] = mapped_column(Text, nullable=True)
    photo_thumb_path: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # raw ingredients weight and the weight after cooking
    total_raw_weight_g: Mapped[Decimal] = mapped_column(Numeric(9, 2), nullable=False, default=0)
    cooked_weight_g: Mapped[Decimal] = mapped_column(Numeric(9, 2), nullable=False, default=0)
    servings: Mapped[Decimal] = mapped_column(Numeric(6, 2), nullable=False, default=1)
    portion_size_g: Mapped[Decimal] = mapped_column(Numeric(8, 2), nullable=False, default=100)

    # totals for the whole cooked dish
    total_kcal: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    total_protein_g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    total_fat_g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    total_carbs_g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    total_fiber_g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)

    # per 100 g of the cooked dish
    kcal_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    protein_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    fat_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    carbs_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    fiber_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)

    is_pinned: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    is_archived: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    use_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    source: Mapped[str] = mapped_column(String(24), nullable=False, default="user")

    items: Mapped[list[RecipeItem]] = relationship(
        back_populates="recipe",
        cascade="all, delete-orphan",
        order_by="RecipeItem.sort_order",
        lazy="selectin",
    )

    __table_args__ = (
        CheckConstraint("cooked_weight_g >= 0 AND total_raw_weight_g >= 0", name="weights_non_negative"),
        CheckConstraint("servings > 0", name="servings_positive"),
        Index("ix_recipes_pinned", "user_id", "is_pinned"),
    )


