class Food(UuidPkMixin, TimestampMixin, Base):
    """A food item per 100 g / 100 ml.

    Global rows (``is_global=True``, ``user_id IS NULL``) come from the
    importers and are shared by every user; custom rows belong to one user.
    ``search_vector_*`` are maintained by a database trigger (see migration
    ``0001``) so importers and the app never have to think about them.
    """

    __tablename__ = "foods"

    user_id: Mapped[uuid.UUID | None] = mapped_column(
        UuidType, ForeignKey("users.id", ondelete="CASCADE"), nullable=True, index=True
    )
    is_global: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, server_default=sa.text("false"))

    name_ru: Mapped[str | None] = mapped_column(String(255), nullable=True)
    name_en: Mapped[str | None] = mapped_column(String(255), nullable=True)
    aliases: Mapped[list[str]] = mapped_column(JsonType, nullable=False, server_default=sa.text("'[]'::jsonb"))
    # kept in sync with `aliases` (trigger) — cheap ILIKE / trgm target
    aliases_text: Mapped[str] = mapped_column(Text, nullable=False, server_default=sa.text("''"))
    brand: Mapped[str | None] = mapped_column(String(160), nullable=True)
    barcode: Mapped[str | None] = mapped_column(String(32), nullable=True, index=True)
    category: Mapped[str | None] = mapped_column(String(120), nullable=True)

    # ---- per 100 g ---------------------------------------------------------
    kcal_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    protein_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    fat_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    carbs_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    fiber_per_100g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    sugar_per_100g: Mapped[Decimal | None] = mapped_column(MACRO, nullable=True)
    saturated_fat_per_100g: Mapped[Decimal | None] = mapped_column(MACRO, nullable=True)
    sodium_mg_per_100g: Mapped[Decimal | None] = mapped_column(MACRO, nullable=True)

    # ---- portions ----------------------------------------------------------
    default_serving_g: Mapped[Decimal | None] = mapped_column(Numeric(8, 2), nullable=True)
    default_serving_label: Mapped[str | None] = mapped_column(String(64), nullable=True)
    is_liquid: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    # ---- provenance --------------------------------------------------------
    source: Mapped[FoodSource] = mapped_column(
        enum_col(FoodSource, "food_source"), nullable=False, default=FoodSource.CUSTOM
    )
    source_id: Mapped[str | None] = mapped_column(String(120), nullable=True)
    source_payload: Mapped[dict[str, Any]] = mapped_column(
        JsonType, nullable=False, server_default=sa.text("'{}'::jsonb")
    )
    # verified = confirmed by the user (AI & seed items start unverified)
    verified: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    use_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    is_archived: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    # ---- search (trigger maintained, never written by the app) -------------
    search_vector_ru: Mapped[str | None] = mapped_column(TSVECTOR, nullable=True, info={"read_only": True})
    search_vector_en: Mapped[str | None] = mapped_column(TSVECTOR, nullable=True, info={"read_only": True})

    __table_args__ = (
        CheckConstraint("kcal_per_100g >= 0", name="kcal_non_negative"),
        CheckConstraint(
            "protein_per_100g >= 0 AND fat_per_100g >= 0 AND carbs_per_100g >= 0", name="macros_non_negative"
        ),
        CheckConstraint(
            "(is_global AND user_id IS NULL) OR (NOT is_global AND user_id IS NOT NULL)",
            name="global_or_owned",
        ),
        CheckConstraint("name_ru IS NOT NULL OR name_en IS NOT NULL", name="at_least_one_name"),
        # importers stay idempotent
        Index(
            "uq_foods_source_ref",
            "source",
            "source_id",
            unique=True,
            postgresql_where=sa.text("source_id IS NOT NULL AND is_global"),
        ),
        Index(
            "uq_foods_custom_user",
            "user_id",
            "barcode",
            unique=True,
            postgresql_where=sa.text("barcode IS NOT NULL AND user_id IS NOT NULL"),
        ),
        Index("ix_foods_barcode_global", "barcode", postgresql_where=sa.text("is_global")),
        Index("ix_foods_search_ru", "search_vector_ru", postgresql_using="gin"),
        Index("ix_foods_search_en", "search_vector_en", postgresql_using="gin"),
        Index(
            "ix_foods_name_ru_trgm",
            sa.text("lower(name_ru) gin_trgm_ops"),
            postgresql_using="gin",
        ),
        Index(
            "ix_foods_name_en_trgm",
            sa.text("lower(name_en) gin_trgm_ops"),
            postgresql_using="gin",
        ),
        Index(
            "ix_foods_aliases_trgm",
            sa.text("lower(aliases_text) gin_trgm_ops"),
            postgresql_using="gin",
        ),
        Index("ix_foods_use_count", "use_count"),
        Index("ix_foods_popular", "is_global", "verified", "use_count"),
    )


