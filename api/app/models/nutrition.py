class MealLog(UuidPkMixin, TimestampMixin, Base):
    """A logged meal. Macros are snapshotted so history never changes."""

    __tablename__ = "meal_logs"

    user_id: Mapped[uuid.UUID] = mapped_column(
        UuidType, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    # client-generated id: repeated POSTs with the same id are idempotent
    client_uuid: Mapped[uuid.UUID] = mapped_column(UuidType, nullable=False, unique=True, default=new_id)

    logged_at: Mapped[datetime] = mapped_column(TzDateTime, nullable=False, index=True)
    # the user's local calendar day (UTC-converted bounds), denormalised for
    # fast day dashboards; always recomputed server-side from the timezone
    local_day: Mapped[date] = mapped_column(Date, nullable=False, index=True)
    meal_type: Mapped[MealType] = mapped_column(enum_col(MealType, "meal_type"), nullable=False, default=MealType.OTHER)
    source: Mapped[MealSource] = mapped_column(
        enum_col(MealSource, "meal_source"), nullable=False, default=MealSource.MANUAL
    )
    title: Mapped[str | None] = mapped_column(String(200), nullable=True)
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    # AI provenance (stage 3): job id + original text; photo is deleted after
    # saving unless the user opted into a 400 px thumbnail.
    ai_job_id: Mapped[uuid.UUID | None] = mapped_column(UuidType, nullable=True)
    ai_input_text: Mapped[str | None] = mapped_column(Text, nullable=True)
    photo_thumb_path: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # ---- snapshot totals ---------------------------------------------------
    kcal: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    protein_g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    fat_g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    carbs_g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    fiber_g: Mapped[Decimal] = mapped_column(MACRO, nullable=False, default=0)
    item_count: Mapped[int] = mapped_column(SmallInteger, nullable=False, default=0)

    is_deleted: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    items: Mapped[list[MealItem]] = relationship(
        back_populates="meal",
        cascade="all, delete-orphan",
        order_by="MealItem.sort_order",
        lazy="selectin",
    )

    __table_args__ = (
        CheckConstraint("kcal >= 0 AND protein_g >= 0 AND fat_g >= 0 AND carbs_g >= 0", name="macros_non_negative"),
        Index("ix_meal_logs_user_day", "user_id", "local_day"),
        Index("ix_meal_logs_user_logged_at", "user_id", "logged_at"),
    )


class MealItem(UuidPkMixin, TimestampMixin, Base):
    __tablename__ = "meal_items"

    user_id: Mapped[uuid.UUID] = mapped_column(
        UuidType, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
